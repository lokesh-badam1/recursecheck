def _rate_stats(audit_path, cfg):
    stamps, per_ip = [], {}
    for line in pathlib.Path(audit_path).read_text().splitlines():
        ev = json.loads(line)
        if ev.get("status") == "DRYRUN":
            continue
        t = datetime.datetime.fromisoformat(ev["ts"]).timestamp()
        stamps.append(t)
        per_ip.setdefault(ev["ip"], []).append(t)
    stamps.sort()
    gaps = [b - a for ts in per_ip.values() for a, b in zip(sorted(ts), sorted(ts)[1:])]
    min_gap = min(gaps) if gaps else None
    peak, j = 0, 0
    for i, t in enumerate(stamps):  # queries in any half-open 1 s window
        while stamps[j] <= t - 1.0:
            j += 1
        peak = max(peak, i - j + 1)
    required = round(1.0 / cfg["target_rate"], 2)
    ok = (min_gap is None or min_gap >= required * 0.95) and peak <= max(1, cfg["global_rate"])
    return {"total": len(stamps), "min_gap": "n/a" if min_gap is None else round(min_gap, 2),
            "required_gap": required, "peak": peak, "ok": ok}


def build(run_dir):
    run_dir = pathlib.Path(run_dir)
    cfg = json.loads((run_dir / "config.json").read_text())
    m = json.loads((run_dir / "metrics.json").read_text())
    evidence = json.loads((run_dir / "evidence.json").read_text())
    with open(run_dir / "results.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["correct"] = r["correct"] == "True"
        r["naive_correct"] = r["naive_correct"] == "True"
    traces = {e["target"]: e["explanation"]["trace"] for e in evidence}
    counts = {l: sum(1 for r in rows if r["verdict"] == l) for l in LABELS}
    counts_text = (f"{counts['Recursive']} recursive, {counts['Refused']} refused, "
                   f"{counts['Authoritative-only']} authoritative-only and {counts['Inconclusive']} inconclusive "
                   f"out of {len(rows)} servers.")
    env = Environment(autoescape=True)
    html = env.from_string(TEMPLATE).render(
        run_name=run_dir.name, generated=datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
        m=m, naive=m["naive_baseline"], cfg=cfg, rows=rows, labels=LABELS, traces=traces,
        exposed=[r for r in rows if r["verdict"] == "Recursive"],
        mismatches=[r for r in rows if not r["correct"]],
        inconclusive=[r for r in rows if r["verdict"] == "Inconclusive"],
        diff=[r for r in rows if r["correct"] != r["naive_correct"]],
        counts_text=counts_text, remediation=REMEDIATION,
        rate=_rate_stats(run_dir / "audit.jsonl", cfg),
        pct=lambda v: "n/a" if v is None else f"{round(v * 100)}%",
    )
    out = run_dir / "exposure_report.html"
    out.write_text(html)
    return out


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: python -m rcheck.report results/<run-dir>")
    print(build(sys.argv[1]))
